// نظام توليد المهام التلقائي
// يولّد المهام بناءً على الخطط المعرّفة كل صباح (من الأحد إلى الخميس)

export interface TaskTemplate {
  id: string;
  title: string;
  description: string;
  category: string;
  priority: "low" | "medium" | "high";
  estimatedTime: string;
}

export interface Plan {
  id: string;
  name: string;
  description: string;
  roleId: string;
  roleName: string;
  isActive: boolean;
  frequency: "daily" | "weekly" | "monthly";
  workDays: string[];
  taskTemplates: TaskTemplate[];
  assignedEmployees: { id: string; name: string; initials: string }[];
}

export interface GeneratedTask {
  id: string;
  title: string;
  description: string;
  assignee: string;
  assigneeId: string;
  assigneeInitials: string;
  status: "pending" | "in_progress" | "completed" | "overdue";
  priority: "low" | "medium" | "high";
  category: string;
  dueDate: string;
  createdAt: string;
  planId: string;
  planName: string;
  templateId: string;
  autoGenerated: boolean;
}

// أيام العمل (الأحد - الخميس)
const arabicDays = ["الأحد", "الإثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت"];

export const getCurrentArabicDay = (): string => {
  const dayIndex = new Date().getDay();
  return arabicDays[dayIndex];
};

export const isWorkDay = (day?: string): boolean => {
  const currentDay = day || getCurrentArabicDay();
  // أيام العمل من الأحد إلى الخميس
  const workDays = ["الأحد", "الإثنين", "الثلاثاء", "الأربعاء", "الخميس"];
  return workDays.includes(currentDay);
};

export const formatDate = (date: Date): string => {
  return date.toISOString().split('T')[0];
};

export const shouldGenerateForPlan = (plan: Plan, currentDay: string): boolean => {
  if (!plan.isActive) return false;
  
  switch (plan.frequency) {
    case "daily":
      return plan.workDays.includes(currentDay);
    case "weekly":
      return plan.workDays.includes(currentDay);
    case "monthly":
      // للخطط الشهرية، نولّد في أول يوم عمل من كل أسبوع المحدد
      return plan.workDays.includes(currentDay);
    default:
      return false;
  }
};

export const generateTasksFromPlan = (plan: Plan, date: Date): GeneratedTask[] => {
  const tasks: GeneratedTask[] = [];
  const dateStr = formatDate(date);
  
  // توزيع المهام على الموظفين المعينين بالتناوب
  plan.taskTemplates.forEach((template, templateIndex) => {
    // نختار موظف بناءً على ترتيب المهمة
    const employeeIndex = templateIndex % plan.assignedEmployees.length;
    const employee = plan.assignedEmployees[employeeIndex];
    
    if (!employee) return;
    
    const task: GeneratedTask = {
      id: `auto-${plan.id}-${template.id}-${dateStr}-${Date.now()}`,
      title: template.title,
      description: template.description,
      assignee: employee.name,
      assigneeId: employee.id,
      assigneeInitials: employee.initials,
      status: "pending",
      priority: template.priority,
      category: template.category,
      dueDate: dateStr,
      createdAt: dateStr,
      planId: plan.id,
      planName: plan.name,
      templateId: template.id,
      autoGenerated: true,
    };
    
    tasks.push(task);
  });
  
  return tasks;
};

export interface TaskGenerationResult {
  success: boolean;
  generatedTasks: GeneratedTask[];
  skippedPlans: { planId: string; planName: string; reason: string }[];
  totalGenerated: number;
  generatedAt: string;
  isWorkDay: boolean;
  currentDay: string;
}

export const generateDailyTasks = (plans: Plan[], date?: Date): TaskGenerationResult => {
  const targetDate = date || new Date();
  const currentDay = getCurrentArabicDay();
  const workDay = isWorkDay(currentDay);
  
  const result: TaskGenerationResult = {
    success: true,
    generatedTasks: [],
    skippedPlans: [],
    totalGenerated: 0,
    generatedAt: formatDate(targetDate),
    isWorkDay: workDay,
    currentDay,
  };
  
  // لا نولّد مهام في الجمعة والسبت (إلا إذا تم طلب ذلك يدوياً)
  if (!workDay && !date) {
    result.success = false;
    return result;
  }
  
  plans.forEach((plan) => {
    if (!plan.isActive) {
      result.skippedPlans.push({
        planId: plan.id,
        planName: plan.name,
        reason: "الخطة غير نشطة",
      });
      return;
    }
    
    if (!shouldGenerateForPlan(plan, currentDay)) {
      result.skippedPlans.push({
        planId: plan.id,
        planName: plan.name,
        reason: `اليوم (${currentDay}) ليس من أيام العمل للخطة`,
      });
      return;
    }
    
    if (plan.assignedEmployees.length === 0) {
      result.skippedPlans.push({
        planId: plan.id,
        planName: plan.name,
        reason: "لا يوجد موظفين معينين",
      });
      return;
    }
    
    const planTasks = generateTasksFromPlan(plan, targetDate);
    result.generatedTasks.push(...planTasks);
  });
  
  result.totalGenerated = result.generatedTasks.length;
  
  return result;
};

